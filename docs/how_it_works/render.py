def _output_path(item: tuple[Path, str]) -> str:
    return item[0].as_posix()


def build_outputs() -> dict[Path, str]:
    """Validate the complete guide and raise if no coherent output set can be built."""

    ambiguity_closure.validate()
    product.validate()
    journey.validate()
    brief.validate()
    diagrams: tuple[Diagram, ...] = (
        ambiguity_closure.DIAGRAM,
        brief.DIAGRAM,
        product.DIAGRAM,
        journey.DIAGRAM,
    )
    outputs: dict[Path, str] = {}
    for diagram in diagrams:
        outputs[OUTPUT_PATHS[diagram.slug]] = render_svg(diagram, DAY_PALETTE)
        outputs[DARK_OUTPUT_PATHS[diagram.slug]] = render_svg(diagram, NIGHT_PALETTE)
    outputs[OUTPUT_PATHS["guide"]] = _guide()
    return dict(sorted(outputs.items(), key=_output_path))


def stale_outputs(root: Path, outputs: Mapping[Path, str]) -> tuple[Path, ...]:
    stale: list[Path] = []
    for relative_path, expected in outputs.items():
        path = root / relative_path
        if not path.is_file() or path.read_text(encoding="utf-8") != expected:
            stale.append(relative_path)
    return tuple(stale)


def write_outputs(root: Path, outputs: Mapping[Path, str]) -> None:
    for relative_path, content in outputs.items():
        path = root / relative_path
        if path.is_file() and path.read_text(encoding="utf-8") == content:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")


def main(arguments: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the visitor-facing How Pinboard works guide.")
    parser.add_argument("--check", action="store_true", help="fail when committed outputs are stale")
    options = parser.parse_args(arguments)
    root = Path(__file__).resolve().parents[2]
    outputs = build_outputs()
    if options.check:
        stale = stale_outputs(root, outputs)
        if stale:
            print("generated visitor guide differs from its source:")
            for path in stale:
                print(f"  {path}")
            print("regenerate and commit: uv run --locked python -m docs.how_it_works.render")
            return 1
        print("generated visitor guide is current")
        return 0
    write_outputs(root, outputs)
    print(f"generated {len(outputs)} visitor-guide files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
