class HowItWorksDocumentationTests(unittest.TestCase):
    def test_source_model_builds_the_complete_visitor_guide(self) -> None:
        outputs = render.build_outputs(ROOT)

        self.assertEqual(
            {
                Path("HOW_IT_WORKS.md"),
                Path("assets/how-it-works/product.svg"),
                Path("assets/how-it-works/layers.svg"),
                Path("assets/how-it-works/journey.svg"),
                Path("assets/how-it-works/database.svg"),
                Path("assets/how-it-works/handover.svg"),
                Path("assets/how-it-works/brief.svg"),
                Path("assets/how-it-works/review-loop.svg"),
                Path("assets/how-it-works/product-dark.svg"),
                Path("assets/how-it-works/layers-dark.svg"),
                Path("assets/how-it-works/journey-dark.svg"),
                Path("assets/how-it-works/database-dark.svg"),
                Path("assets/how-it-works/handover-dark.svg"),
                Path("assets/how-it-works/brief-dark.svg"),
                Path("assets/how-it-works/review-loop-dark.svg"),
            },
            outputs.keys(),
        )
        guide = outputs[Path("HOW_IT_WORKS.md")]
        self.assertEqual(7, guide.count("<picture>"))
        self.assertEqual(7, guide.count('media="(prefers-color-scheme: dark)"'))
        for slug in ("product", "layers", "journey", "database", "handover", "brief", "review-loop"):
            self.assertIn(f'srcset="assets/how-it-works/{slug}-dark.svg"', guide)
            self.assertIn(f'src="assets/how-it-works/{slug}.svg"', guide)

    def test_diagrams_use_the_approved_reading_surfaces(self) -> None:
        outputs = render.build_outputs(ROOT)

        for path, svg in outputs.items():
            if path.suffix != ".svg":
                continue
            with self.subTest(path=path):
                palette = NIGHT_PALETTE if path.stem.endswith("-dark") else DAY_PALETTE
                self.assertIn(f'fill="{palette.canvas}"', svg)
                self.assertIn(f'stroke="{palette.grid}"', svg)
                self.assertIn(f"stroke: {palette.connector}", svg)
                self.assertIn(f'fill="{palette.primary}"', svg)
                self.assertIn("<metadata>Generated by docs.how_it_works</metadata>", svg)
                self.assertIn('<pattern id="grid"', svg)
                self.assertNotIn("linearGradient", svg)
                self.assertNotIn("feDropShadow", svg)

        for slug in ("product", "layers", "journey", "database", "handover", "brief", "review-loop"):
            day = outputs[Path(f"assets/how-it-works/{slug}.svg")]
            night = outputs[Path(f"assets/how-it-works/{slug}-dark.svg")]
            with self.subTest(slug=slug):
                self.assertEqual(
                    re.sub(r"#[0-9a-fA-F]{3,6}\b", "#COLOR", day),
                    re.sub(r"#[0-9a-fA-F]{3,6}\b", "#COLOR", night),
                )

    def test_diagrams_expose_accessible_names_and_descriptions(self) -> None:
        outputs = render.build_outputs(ROOT)
        namespace = {"svg": "http://www.w3.org/2000/svg"}

        for path, svg in outputs.items():
            if path.suffix != ".svg":
                continue
            with self.subTest(path=path):
                root = ElementTree.fromstring(svg)
                labelled_by = root.attrib["aria-labelledby"].split()
                self.assertEqual("img", root.attrib["role"])
                self.assertEqual(2, len(labelled_by))
                title = root.find("svg:title", namespace)
                description = root.find("svg:desc", namespace)
                self.assertIsNotNone(title)
                self.assertIsNotNone(description)
                assert title is not None
                assert description is not None
                self.assertEqual([title.attrib["id"], description.attrib["id"]], labelled_by)
                self.assertTrue(title.text)
                self.assertTrue(description.text)

